uint16_t uart_crc16(const void *data, size_t len)
{
	const uint8_t *p = data;
	uint16_t crc = 0xFFFF;

	while (len--)
		crc = (crc << 8) ^ crc16_table[((crc >> 8) ^ *p++) & 0xFF];

	return crc;
}
